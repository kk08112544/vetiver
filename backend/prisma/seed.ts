async function main() {
  console.log('🌱 กำลังล้างข้อมูลเดิม...');
  await prisma.section.deleteMany();
  await prisma.topic.deleteMany();

  console.log('🌱 กำลังเพิ่มข้อมูลหญ้าแฝก...');
  for (const t of topics) {
    await prisma.topic.create({
      data: {
        slug: t.slug,
        order: t.order,
        title: t.title,
        subtitle: t.subtitle,
        icon: t.icon,
        accent: t.accent,
        intro: t.intro,
        sections: {
          create: t.sections.map((s, i) => ({
            order: i + 1,
            heading: s.heading,
            body: s.body ?? null,
            items: JSON.stringify(s.items ?? []),
          })),
        },
      },
    });
    console.log(`   ✓ ${t.title}`);
  }
  console.log('✅ เพิ่มข้อมูลเรียบร้อย');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
